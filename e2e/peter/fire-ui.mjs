// Explicit browser acceptance against a local candidate and Peter's existing
// backend. Apart from signing in, this test does not write business data.
import assert from 'node:assert/strict'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { chromium } from '../../.runtime/peter/deployment/browser/node_modules/playwright/index.mjs'

const origin = process.env.PETER_FIRE_ORIGIN || 'http://127.0.0.1:4217'
const destination = 'artifacts/fire-ui-implementation-20261017'
mkdirSync(destination, { recursive: true })
const account = JSON.parse(readFileSync('.runtime/peter/deployment/account.json', 'utf8'))
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const context = await browser.newContext({ ignoreHTTPSErrors: true, locale: 'zh-CN', viewport: { width: 1586, height: 992 } })
const page = await context.newPage()
page.setDefaultTimeout(30000)
await page.addLocatorHandler(page.locator('.guide__skip'), button => button.click())
const errors = []
const checks = []
page.on('pageerror', error => errors.push({ message: error.message, stack: error.stack, url: page.url() }))
const pass = text => { checks.push(text); console.log('PASS ' + text) }
const screenshot = name => page.screenshot({ path: `${destination}/${name}.png`, fullPage: true })
const background = selector => page.locator(selector).first().evaluate(el => getComputedStyle(el).backgroundColor)
const go = async path => {
  await page.goto(origin + path, { waitUntil: 'domcontentloaded' })
  await page.locator('.fire-sidebar-brand').first().waitFor({ state: 'attached' })
  if (page.viewportSize().width > 760) {
    await page.locator('.visual-user-menu__identity').filter({ hasText: account.email }).waitFor({ timeout: 90000 })
  }
}
try {
  await page.goto(`${origin}/auth/start?lang=zh-CN`)
  await page.locator('#email').waitFor({ timeout: 90000 })
  assert.equal(await page.getByRole('heading', { name: '登录火种', exact: true }).count(), 1)
  await screenshot('01-login')
  await page.locator('#email').fill(account.email)
  await page.locator('#password').fill(account.password)
  await page.locator('button[type=submit]').click()
  await page.locator('.fire-sidebar-brand').first().waitFor({ timeout: 90000 })
  pass('Branded native login reaches the real workspace')
  await go('/platform/design-system')
  await page.getByRole('heading', { name: '火种组件库' }).waitFor()
  assert.equal(await background('.fire-library'), 'rgb(11, 11, 13)')
  await page.getByRole('button', { name: '保存示例', exact: true }).click()
  await page.locator('.fire-library__status').filter({ hasText: '示例已保存' }).waitFor()
  await page.getByRole('button', { name: '打开对话框', exact: true }).click()
  await page.locator('.t-dialog:visible').waitFor()
  assert.equal(await background('.t-dialog:visible'), 'rgb(21, 21, 24)')
  await screenshot('02-component-dialog')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '查看来源', exact: true }).click()
  await page.locator('.t-drawer__content-wrapper:visible').waitFor()
  assert.equal(await background('.t-drawer__content-wrapper:visible'), 'rgb(21, 21, 24)')
  await page.locator('.t-drawer__content-wrapper:visible .t-drawer__close-btn').click()
  await page.getByPlaceholder('搜索知识…', { exact: true }).fill('自然表达')
  await page.locator('.fire-library__fields .t-select__wrap input').click()
  await page.getByText('社交媒体自我价值展示', { exact: true }).last().click()
  await screenshot('03-components')
  pass('Shared controls save, select, open and close dark teleported dialogs and drawers')
  await go('/platform/creatChat')
  await page.getByRole('heading', { name: '今天，想聊些什么？' }).waitFor()
  assert.equal(await background('.visual-new-chat-view'), 'rgb(11, 11, 13)')
  await page.locator('.visual-chat-composer__surface').waitFor()
  await screenshot('04-new-chat')
  pass('New chat uses the shared composer and Fire branding')
  await go('/platform/knowledge-bases/961f9976-ae42-4bc4-bafe-1dfa4506f0c9?tab=wiki&slug=summary/e0fc0355-7ea2-4921-a09a-ceebb038327d')
  await page.locator('.wiki-sidebar').waitFor({ timeout: 90000 })
  await page.locator('.wiki-reader-title').first().waitFor({ timeout: 90000 })
  await page.locator('.wiki-reader-body').first().waitFor()
  assert.equal(await background('.wiki-content'), 'rgb(11, 11, 13)')
  await page.locator('.fire-wiki-outline nav button').first().waitFor()
  await page.locator('.fire-wiki-outline nav button').last().click()
  await screenshot('05-wiki')
  const wikiURL = page.url()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.locator('.wiki-reader-body').first().waitFor({ timeout: 90000 })
  assert.equal(page.url(), wikiURL)
  pass('Real course Wiki opens, reads and survives refresh with its deep link')
  await go('/platform/knowledge-bases/961f9976-ae42-4bc4-bafe-1dfa4506f0c9?tab=graph')
  await page.locator('.wiki-graph-canvas canvas').first().waitFor({ timeout: 90000 })
  await page.locator('.wiki-graph-legend').waitFor({ timeout: 90000 })
  await page.getByRole('button', { name: '适应屏幕', exact: true }).click()
  await screenshot('05b-graph')
  pass('Native course graph renders and its fit-to-view action works')
  await go('/platform/chat/21022a55-8d1d-4fab-a988-cfa536f70e1b')
  await page.locator('.visual-assistant-message').first().waitFor({ timeout: 90000 })
  await page.locator('.citation-kb').first().click()
  await page.locator('.visual-references-panel').waitFor()
  await page.locator('.visual-reference-item').first().waitFor()
  await screenshot('06-real-chat')
  await page.locator('.visual-references-panel__close').click()
  pass('Existing real DeepSeek conversation and source panel render without a new model call')
  await go('/platform/customers')
  await page.locator('.customer-page').first().waitFor()
  await page.getByRole('heading', { name: '目标', exact: true }).waitFor()
  assert.equal(await background('.customer-page'), 'rgb(11, 11, 13)')
  assert.equal(await page.locator('[data-guide="nav-customers"].is-active').count(), 1)
  await screenshot('07-customers')
  await page.getByRole('button', { name: '新建目标', exact: true }).click()
  const targetDialog = page.getByRole('dialog', { name: '新建目标', exact: true })
  await targetDialog.waitFor()
  await targetDialog.getByText('目标名称', { exact: false }).first().waitFor()
  await screenshot('07b-target-form')
  await targetDialog.getByRole('button', { name: '取消', exact: true }).click()
  pass('Targets use the renamed dedicated navigation and page title')
  await go('/platform/settings?section=general')
  await page.locator('.visual-general-settings').waitFor()
  assert.equal(await page.locator('#visual-theme-select').count(), 0)
  await screenshot('08-settings')
  pass('Settings retain functional controls and do not offer a theme the brand cannot apply')
  await page.setViewportSize({ width: 390, height: 844 })
  await go('/platform/creatChat')
  await page.locator('.visual-mobile-header .fire-brand').waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true)
  await screenshot('09-mobile')
  await page.locator('.visual-mobile-header > button').first().click()
  await page.locator('.visual-sidebar:not(.is-collapsed)').waitFor()
  await screenshot('10-mobile-menu')
  pass('Mobile brand, navigation and composer fit a 390px viewport')
  assert.deepEqual(errors, [])
  writeFileSync(`${destination}/acceptance.json`, JSON.stringify({ origin, checks, errors, accepted: true }, null, 2) + '\n')
} catch (error) {
  await screenshot('failure').catch(() => {})
  writeFileSync(`${destination}/acceptance.json`, JSON.stringify({ origin, checks, errors, accepted: false, failure: error.message }, null, 2) + '\n')
  throw error
} finally { await browser.close() }
