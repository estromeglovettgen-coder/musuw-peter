// Reuse the shipped TDesign symbols; do not duplicate the icon drawing system.
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '../weknora/frontend');
const names = new Set();
async function collect(folder) {
  for (const entry of await readdir(folder, { withFileTypes: true })) {
    const path = resolve(folder, entry.name);
    if (entry.isDirectory()) await collect(path);
    else if (/\.(vue|ts|js|json)$/.test(entry.name)) {
      const source = await readFile(path, 'utf8');
      for (const match of source.matchAll(/['"`]([a-z][a-z0-9-]*)['"`]/g)) names.add(match[1]);
    }
  }
}
await collect(resolve(root, 'src'));
const full = await readFile(resolve(root, 'public/tdesign-icons/0.4.1/fonts/index.js'), 'utf8');
const symbols = [...full.matchAll(/<symbol\b[\s\S]*?<\/symbol>/g)].map(match => match[0]);
const selected = symbols.filter(symbol => names.has(symbol.match(/id="t-icon-([^"]+)"/)[1]));
if (!selected.length) throw new Error('No native TDesign symbols found');
const svg = '<svg data-workspace-icons="core" style="position:absolute;width:0;height:0;visibility:hidden" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">' + selected.join('') + '</svg>';
await writeFile(resolve(root, 'public/tdesign-icons/0.4.1/fonts/workspace.js'), '// Generated by tools/build-workspace-icons.mjs from the attributed TDesign sprite.\n(() => { document.body.insertAdjacentHTML("afterbegin", ' + JSON.stringify(svg) + '); })();\n');
console.log(`Native workspace icons: ${selected.length}/${symbols.length} symbols`);
